interface IconProps {
  size?: number;
  className?: string;
  style?: React.CSSProperties;
}

function icon(path: string) {
  return function Icon({ size = 16, className, style }: IconProps) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={1.5}
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        style={style}
      >
        {path.split('|').map((d, i) => (
          d.startsWith('c:') ? (
            <circle key={i} cx={d.split(',')[1]} cy={d.split(',')[2]} r={d.split(',')[3]} />
          ) : (
            <path key={i} d={d} />
          )
        ))}
      </svg>
    );
  };
}

